# Quantas milhas há em 10 quilômetros? Dica: uma milha equivale a 1,61 quilômetros.
print(10 / 1.61)

# Se você correr 10 quilômetros em 42 minutos e 42 segundos, qual é seu passo médio?
# (tempo por milha em minutos e segundos)? Qual é a sua velocidade média em milhas por hora?
print((42 * 60 + 42) / (10 / 1.61))  # Passo médio em segundos por milha